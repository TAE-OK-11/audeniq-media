#!/usr/bin/env python3
"""Generate crates/media-json/src/ryu_tables.rs: Ryu's f64 power-of-5 tables.

DOUBLE_POW5_INV_SPLIT[i] = floor(2^(bitlen(5^i) - 1 + 125) / 5^i) + 1
DOUBLE_POW5_SPLIT[i]     = 5^i scaled to its top 125 bits (floor)
each stored as [low 64 bits, high 64 bits], as in Ulf Adams' Ryu (d2s.c).
"""
import sys

INV_BITCOUNT = 125
BITCOUNT = 125
INV_SIZE = 342
SIZE = 326
MASK = (1 << 64) - 1


def pair(v):
    assert v < 1 << 128
    return f"[{v & MASK:#x}, {v >> 64:#x}]"


out = ["// @generated by crates/media-json/scripts/gen_ryu_tables.py; do not edit by hand.",
       "//! Ryu's power-of-5 multipliers for f64 (Ulf Adams, Apache-2.0 OR BSL-1.0).", ""]
out.append(f"pub(crate) static DOUBLE_POW5_INV_SPLIT: [[u64; 2]; {INV_SIZE}] = [")
for i in range(INV_SIZE):
    p = 5 ** i
    j = p.bit_length() - 1 + INV_BITCOUNT
    out.append(f"    {pair((1 << j) // p + 1)},")
out.append("];")
out.append("")
out.append(f"pub(crate) static DOUBLE_POW5_SPLIT: [[u64; 2]; {SIZE}] = [")
for i in range(SIZE):
    p = 5 ** i
    shift = p.bit_length() - BITCOUNT
    out.append(f"    {pair(p >> shift if shift >= 0 else p << -shift)},")
out.append("];")
sys.stdout.write("\n".join(out) + "\n")
